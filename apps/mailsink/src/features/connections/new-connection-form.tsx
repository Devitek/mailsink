import { Trans, useLingui } from '@lingui/react/macro'
import type { ConnectionKind, CreatedConnection } from '@mailsink/contracts'
import { Button, SegmentedControl } from '@mailsink/ui'
import { useForm } from '@tanstack/react-form'
import { useState } from 'react'
import { firstError, TextField } from '../workspaces/form-fields'
import { connectionDefaults, connectionSchema } from './connection-form'
import { ConnectionKindHint } from './connection-kind-hint'
import { KIND_OPTIONS } from './kinds'
import { PanelHeader } from './panel'
import { useConnectionMutations } from './queries'

const touchedError = (meta: { isTouched: boolean; errors: readonly unknown[] }) =>
  meta.isTouched ? firstError(meta.errors) : undefined

type NewConnectionFormProps = {
  slug: string
  onCreated: (connection: CreatedConnection) => void
  onCancel: () => void
}

// « Nouvelle connexion » panel of the prototype (#38): kind segmented in the header, then
// the fields of that kind; secrets are generated by the server and shown once afterwards.
export function NewConnectionForm({ slug, onCreated, onCancel }: NewConnectionFormProps) {
  const { t } = useLingui()
  const { create } = useConnectionMutations(slug)
  const [usernameTaken, setUsernameTaken] = useState(false)
  const schema = connectionSchema({
    nameTooLong: t`80 characters at most.`,
    usernameInvalid: t`3 to 64 letters, digits, dots, dashes or underscores.`,
    rateInvalid: t`A whole number of requests per second, or empty.`,
  })
  const form = useForm({
    defaultValues: connectionDefaults(),
    validators: { onBlur: schema, onSubmit: schema },
    onSubmit: async ({ value }) => {
      const result = await create.mutateAsync(value)
      if (result.ok) onCreated(result.connection)
      else setUsernameTaken(true)
    },
  })

  return (
    <form
      noValidate
      onSubmit={(event) => {
        event.preventDefault()
        void form.handleSubmit()
      }}
    >
      <form.Field name="kind">
        {(field) => (
          <PanelHeader
            title={<Trans>New connection</Trans>}
            subtitle={<Trans>Choose the provider to emulate</Trans>}
          >
            <SegmentedControl
              aria-label={t`Connection kind`}
              options={KIND_OPTIONS}
              value={field.state.value}
              onValueChange={(kind: ConnectionKind) => field.handleChange(kind)}
            />
          </PanelHeader>
        )}
      </form.Field>
      <div className="flex flex-col gap-[18px] p-[22px]">
        <form.Field name="name">
          {(field) => (
            <TextField
              label={<Trans>Name</Trans>}
              name={field.name}
              value={field.state.value}
              onChange={field.handleChange}
              onBlur={field.handleBlur}
              error={touchedError(field.state.meta)}
              placeholder={t`e.g. resend-transactional`}
              mono
              autoFocus
            />
          )}
        </form.Field>
        <form.Subscribe selector={(state) => state.values.kind}>
          {(kind) => (
            <>
              {kind === 'smtp' && (
                <form.Field name="smtpUsername">
                  {(field) => (
                    <TextField
                      label={<Trans>SMTP username</Trans>}
                      name={field.name}
                      value={field.state.value}
                      onChange={(value) => {
                        setUsernameTaken(false)
                        field.handleChange(value)
                      }}
                      onBlur={field.handleBlur}
                      error={
                        usernameTaken
                          ? t`This SMTP username is already taken.`
                          : touchedError(field.state.meta)
                      }
                      description={<Trans>Optional: generated from the workspace slug.</Trans>}
                      mono
                    />
                  )}
                </form.Field>
              )}
              <form.Field name="rateLimit">
                {(field) => (
                  <TextField
                    label={<Trans>Rate limit override</Trans>}
                    name={field.name}
                    value={field.state.value}
                    onChange={field.handleChange}
                    onBlur={field.handleBlur}
                    error={touchedError(field.state.meta)}
                    description={<Trans>Optional, else the workspace value.</Trans>}
                    inputMode="numeric"
                    suffix="req/s"
                    mono
                  />
                )}
              </form.Field>
              <ConnectionKindHint kind={kind} />
            </>
          )}
        </form.Subscribe>
        {create.isError && (
          <p role="alert" className="text-sm text-ms-danger">
            <Trans>The connection could not be created. Try again.</Trans>
          </p>
        )}
        <div className="flex justify-end gap-2.5">
          <Button type="button" variant="outline" onClick={onCancel}>
            <Trans>Cancel</Trans>
          </Button>
          <form.Subscribe selector={(state) => state.isSubmitting}>
            {(submitting) => (
              <Button type="submit" variant="primary" disabled={submitting}>
                <Trans>Create the connection</Trans>
              </Button>
            )}
          </form.Subscribe>
        </div>
      </div>
    </form>
  )
}
