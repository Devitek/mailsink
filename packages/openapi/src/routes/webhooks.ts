import {
  ListWebhookDeliveriesQuery,
  ListWebhookDeliveriesResponse,
  ListWebhookEndpointsQuery,
  ListWebhookEndpointsResponse,
  ReplayRequest,
  WebhookDeliveryDetail,
  WebhookDeliveryId,
  WebhookDeliveryView,
  WebhookEndpointId,
  WebhookEndpointInput,
  WebhookEndpointPatch,
  WebhookEndpointView,
  WebhookEndpointWithSecret,
  WebhookPreviewRequest,
  WebhookPreviewResponse,
  WebhookTestRequest,
} from '@mailsink/contracts'
import { z } from 'zod'
import type { RouteSpec } from '../route'

const EndpointParams = z.object({ id: WebhookEndpointId })
const DeliveryParams = z.object({ id: WebhookDeliveryId })
const webhooks = { tag: 'Capture: webhooks', auth: 'workspace' } as const

/** Webhook endpoints, delivery log and replay (03-contracts, « Webhooks »). */
export const WEBHOOK_ROUTES: RouteSpec[] = [
  {
    ...webhooks,
    operationId: 'listWebhooks',
    method: 'get',
    path: '/capture/webhooks',
    summary: 'Webhook endpoints of a scope and of the workspace',
    query: ListWebhookEndpointsQuery,
    success: [{ status: 200, description: 'The endpoints.', schema: ListWebhookEndpointsResponse }],
  },
  {
    ...webhooks,
    operationId: 'createWebhook',
    method: 'post',
    path: '/capture/webhooks',
    summary: 'Create a webhook endpoint (secret answered once)',
    body: WebhookEndpointInput,
    success: [{ status: 201, description: 'Created.', schema: WebhookEndpointWithSecret }],
  },
  {
    ...webhooks,
    operationId: 'getWebhook',
    method: 'get',
    path: '/capture/webhooks/{id}',
    summary: 'Webhook endpoint detail',
    params: EndpointParams,
    success: [{ status: 200, description: 'The endpoint.', schema: WebhookEndpointView }],
  },
  {
    ...webhooks,
    operationId: 'updateWebhook',
    method: 'patch',
    path: '/capture/webhooks/{id}',
    summary: 'Edit a webhook endpoint (`secret` set when rotated)',
    params: EndpointParams,
    body: WebhookEndpointPatch,
    success: [{ status: 200, description: 'The endpoint.', schema: WebhookEndpointWithSecret }],
  },
  {
    ...webhooks,
    operationId: 'deleteWebhook',
    method: 'delete',
    path: '/capture/webhooks/{id}',
    summary: 'Delete a webhook endpoint',
    params: EndpointParams,
    success: [
      { status: 200, description: 'Deleted.', schema: z.object({ id: WebhookEndpointId }) },
    ],
  },
  {
    ...webhooks,
    operationId: 'previewWebhook',
    method: 'post',
    path: '/capture/webhooks/preview',
    summary: 'Sample payload and headers of a format, secret masked',
    body: WebhookPreviewRequest,
    success: [{ status: 200, description: 'The sample.', schema: WebhookPreviewResponse }],
  },
  {
    ...webhooks,
    operationId: 'testWebhook',
    method: 'post',
    path: '/capture/webhooks/{id}/test',
    summary: 'Send one signed sample event (logged as a delivery)',
    params: EndpointParams,
    body: WebhookTestRequest,
    bodyOptional: true,
    success: [{ status: 200, description: 'The delivery.', schema: WebhookDeliveryDetail }],
  },
  {
    ...webhooks,
    operationId: 'listWebhookDeliveries',
    method: 'get',
    path: '/capture/webhooks/deliveries',
    summary: 'Webhook delivery log, newest first',
    query: ListWebhookDeliveriesQuery,
    success: [{ status: 200, description: 'One page.', schema: ListWebhookDeliveriesResponse }],
  },
  {
    ...webhooks,
    operationId: 'getWebhookDelivery',
    method: 'get',
    path: '/capture/webhooks/deliveries/{id}',
    summary: 'Delivery body and every attempt with its exact headers',
    params: DeliveryParams,
    success: [{ status: 200, description: 'The delivery.', schema: WebhookDeliveryDetail }],
  },
  {
    ...webhooks,
    operationId: 'replayWebhookDelivery',
    method: 'post',
    path: '/capture/webhooks/deliveries/{id}/replay',
    summary: 'Replay a delivery (`exact` or `resign`)',
    params: DeliveryParams,
    body: ReplayRequest,
    bodyOptional: true,
    success: [{ status: 202, description: 'The new delivery.', schema: WebhookDeliveryView }],
    errors: ['conflict'],
  },
]
