import {
  ConnectionId,
  ConnectionInput,
  ConnectionView,
  CreatedConnection,
  CreateWorkspaceRequest,
  CreateWorkspaceResponse,
  ListWorkspacesQuery,
  ListWorkspacesResponse,
  RotatedWorkspaceKey,
  UpdateConnectionRequest,
  UpdateWorkspaceRequest,
  WorkspaceDetail,
  WorkspaceRef,
  WorkspaceView,
} from '@mailsink/contracts'
import { z } from 'zod'
import type { RouteSpec } from '../route'

const Ref = z.object({ id: WorkspaceRef.meta({ description: 'Workspace id (`ws_…`) or slug.' }) })
const ConnectionParams = z.object({ id: WorkspaceRef, connectionId: ConnectionId })
const admin = { tag: 'Admin', auth: 'admin' } as const
const deleted = [{ status: 204, description: 'Deleted.' }]

/** Admin API (03-contracts, « Admin »): Admin key only (D41). */
export const ADMIN_ROUTES: RouteSpec[] = [
  {
    ...admin,
    operationId: 'createWorkspace',
    method: 'post',
    path: '/admin/workspaces',
    summary: 'Create a workspace and its connections',
    description: 'Secrets (connection keys, SMTP passwords, workspace key) are answered once.',
    body: CreateWorkspaceRequest,
    success: [{ status: 201, description: 'Created.', schema: CreateWorkspaceResponse }],
    errors: ['conflict'],
  },
  {
    ...admin,
    operationId: 'listWorkspaces',
    method: 'get',
    path: '/admin/workspaces',
    summary: 'List workspaces',
    query: ListWorkspacesQuery,
    success: [{ status: 200, description: 'One page.', schema: ListWorkspacesResponse }],
  },
  {
    ...admin,
    operationId: 'getWorkspace',
    method: 'get',
    path: '/admin/workspaces/{id}',
    summary: 'Workspace detail',
    params: Ref,
    success: [{ status: 200, description: 'The workspace.', schema: WorkspaceDetail }],
  },
  {
    ...admin,
    operationId: 'updateWorkspace',
    method: 'patch',
    path: '/admin/workspaces/{id}',
    summary: 'Edit a workspace (name, retention, rate limit, quota, simulation)',
    params: Ref,
    body: UpdateWorkspaceRequest,
    success: [{ status: 200, description: 'The workspace.', schema: WorkspaceView }],
  },
  {
    ...admin,
    operationId: 'deleteWorkspace',
    method: 'delete',
    path: '/admin/workspaces/{id}',
    summary: 'Delete a workspace and everything it owns',
    params: Ref,
    success: deleted,
  },
  {
    ...admin,
    operationId: 'rotateWorkspaceKey',
    method: 'post',
    path: '/admin/workspaces/{id}/key/rotate',
    summary: 'New workspace key, the previous ones revoked (D207)',
    params: Ref,
    success: [{ status: 200, description: 'The new key, once.', schema: RotatedWorkspaceKey }],
  },
  {
    ...admin,
    operationId: 'createConnection',
    method: 'post',
    path: '/admin/workspaces/{id}/connections',
    summary: 'Add a connection (secrets answered once)',
    params: Ref,
    body: ConnectionInput,
    success: [{ status: 201, description: 'Created.', schema: CreatedConnection }],
    errors: ['conflict'],
  },
  {
    ...admin,
    operationId: 'updateConnection',
    method: 'patch',
    path: '/admin/workspaces/{id}/connections/{connectionId}',
    summary: 'Rename, disable or enable a connection',
    params: ConnectionParams,
    body: UpdateConnectionRequest,
    success: [{ status: 200, description: 'The connection.', schema: ConnectionView }],
    errors: ['conflict'],
  },
  {
    ...admin,
    operationId: 'deleteConnection',
    method: 'delete',
    path: '/admin/workspaces/{id}/connections/{connectionId}',
    summary: 'Delete a connection',
    params: ConnectionParams,
    success: deleted,
  },
  {
    ...admin,
    operationId: 'rotateConnection',
    method: 'post',
    path: '/admin/workspaces/{id}/connections/{connectionId}/rotate',
    summary: 'New connection secret, the previous one revoked',
    params: ConnectionParams,
    success: [{ status: 200, description: 'The new secrets, once.', schema: CreatedConnection }],
  },
]
