import {
  type Executor,
  enqueueJobs,
  findSuppressedEmails,
  insertMessageGraph,
  type NewAttachment,
  type NewMessageEvent,
  type NewMessageRecipient,
  newId,
} from '@mailsink/db'
import { createDbBlobStore } from '../blobs/db-store'
import type { BlobStore } from '../blobs/store'
import type { StreamFrame } from '../events/bus'
import { attachmentContentType } from './compose-eml'
import type { IngestTarget, NormalizedEmail } from './normalize'
import type { PreparedEmail } from './prepare'
import { ingestionFrames } from './stream-frames'

export type IngestedStatus = 'queued' | 'suppressed'

export interface IngestedMessage {
  id: string
  providerMessageId: string
  status: IngestedStatus
}

/** Payload of the `simulate_delivery` job handed to the workers (#21). */
export type SimulateDeliveryPayload = { messageId: string }

type Recipient = { kind: 'to' | 'cc' | 'bcc'; email: string; name: string | null }

/** One row per address (D10): an address listed twice keeps its first kind (to > cc > bcc). */
export function recipientsOf(email: NormalizedEmail): Recipient[] {
  const seen = new Map<string, Recipient>()
  for (const kind of ['to', 'cc', 'bcc'] as const) {
    for (const a of email[kind]) {
      if (!seen.has(a.email)) seen.set(a.email, { kind, email: a.email, name: a.name ?? null })
    }
  }
  return [...seen.values()]
}

export interface PersistOptions {
  idempotencyKey?: string
  /** Defaults to the database store bound to the transaction. */
  blobs?: BlobStore
  /**
   * Receives the `message.created` and ingestion event frames, for the caller to publish
   * once the transaction has committed (D6).
   */
  frames?: StreamFrame[]
}

/**
 * Transactional part of the pipeline (call inside a transaction): blobs, message,
 * per-recipient rows with the suppression check, `accepted` and `suppressed` events, and
 * one `simulate_delivery` job per message that still has a queued recipient. Events
 * generated by Mailsink itself carry the `simulation` origin.
 */
export async function persistEmails(
  tx: Executor,
  target: IngestTarget,
  prepared: readonly PreparedEmail[],
  options: PersistOptions = {},
): Promise<IngestedMessage[]> {
  const blobs = options.blobs ?? createDbBlobStore(tx)
  const everyAddress = prepared.flatMap((p) => recipientsOf(p.email).map((r) => r.email))
  const suppressed = await findSuppressedEmails(tx, target.workspaceId, [...new Set(everyAddress)])
  const results: IngestedMessage[] = []
  const jobs: { messageId: string }[] = []

  for (const { id, email, raw, links, createdAt } of prepared) {
    const rawBlob = await blobs.put(target.workspaceId, raw)
    const attachmentRows: NewAttachment[] = []
    for (const a of email.attachments) {
      const blob = await blobs.put(target.workspaceId, a.content)
      attachmentRows.push({
        id: newId('att'),
        messageId: id,
        filename: a.filename,
        contentType: attachmentContentType(a),
        contentId: a.contentId ?? null,
        disposition: a.contentId ? 'inline' : 'attachment',
        sizeBytes: a.content.byteLength,
        blobId: blob.id,
      })
    }
    const recipients: NewMessageRecipient[] = recipientsOf(email).map((r) => ({
      id: newId('rcp'),
      messageId: id,
      workspaceId: target.workspaceId,
      ...r,
      status: suppressed.has(r.email) ? 'suppressed' : 'queued',
      statusReason: suppressed.has(r.email) ? 'on the suppression list' : null,
      updatedAt: createdAt,
    }))
    const status: IngestedStatus = recipients.some((r) => r.status === 'queued')
      ? 'queued'
      : 'suppressed'
    const event = (type: 'accepted' | 'suppressed', recipientEmail: string | null) =>
      ({
        id: newId('evt'),
        workspaceId: target.workspaceId,
        messageId: id,
        recipientEmail,
        type,
        origin: 'simulation',
        data: type === 'suppressed' ? { reason: 'on the suppression list' } : null,
        occurredAt: createdAt,
      }) satisfies NewMessageEvent
    const events = [
      event('accepted', null),
      ...recipients
        .filter((r) => r.status === 'suppressed')
        .map((r) => event('suppressed', r.email)),
    ]
    const providerMessageId = email.providerMessageId ?? id
    await insertMessageGraph(tx, {
      message: {
        id,
        workspaceId: target.workspaceId,
        connectionId: target.connectionId,
        source: target.source,
        providerMessageId,
        from: email.from,
        replyTo: email.replyTo.length > 0 ? email.replyTo : null,
        subject: email.subject,
        html: email.html,
        text: email.text,
        headers: email.headers,
        tags: email.tags,
        metadata: email.metadata,
        templateRef: email.templateRef ?? null,
        links,
        rawBlobId: rawBlob.id,
        sizeBytes: raw.byteLength,
        status,
        idempotencyKey: options.idempotencyKey ?? null,
        createdAt,
        statusUpdatedAt: createdAt,
      },
      recipients,
      attachments: attachmentRows,
      events,
    })
    options.frames?.push(
      ...ingestionFrames({
        id,
        target,
        email,
        recipients,
        attachmentRows,
        status,
        createdAt,
        events,
      }),
    )
    if (status === 'queued') jobs.push({ messageId: id })
    results.push({ id, providerMessageId, status })
  }
  await enqueueJobs(
    tx,
    jobs.map((payload) => ({
      kind: 'simulate_delivery' as const,
      workspaceId: target.workspaceId,
      payload: payload satisfies SimulateDeliveryPayload,
    })),
  )
  return results
}
