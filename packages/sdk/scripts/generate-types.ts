// Expands every type of `src/contract-types.ts` into plain TypeScript (D260): the published
// declarations then carry object shapes instead of the Zod schemas they were derived from.
// The TypeScript declaration emitter does the expansion: a value typed `Expand<T>` is
// printed structurally, with no alias left to reference the schemas. It drops the JSDoc of
// the contract fields, put back by scripts/type-docs.ts.
//
// Writes `src/types.ts` and `test/types-fidelity.ts` (mutual assignability of each pair,
// checked by `pnpm typecheck`). Run: `pnpm --filter @devitek/mailsink generate:types`.
import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { contractDocs, insertDocs } from './type-docs.ts'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const source = readFileSync(join(root, 'src/contract-types.ts'), 'utf8')
const names = [...source.matchAll(/^export type (\w+)/gm)].map((m) => m[1] as string)

const bin = (name: string) => join(root, '../../node_modules/.bin', name)
const work = join(root, '.types-gen')
rmSync(work, { recursive: true, force: true })
mkdirSync(work)
try {
  writeFileSync(
    join(work, 'expand.ts'),
    [
      "import type * as S from '../src/contract-types'",
      'type Expand<T> = T extends Date | ((...args: never[]) => unknown)',
      '  ? T',
      '  : T extends object',
      '    ? T extends infer O',
      '      ? { [K in keyof O]: Expand<O[K]> }',
      '      : never',
      '    : T',
      'declare function expand<T>(): Expand<T>',
      ...names.map((name) => `export const ${name} = expand<S.${name}>()`),
    ].join('\n'),
  )
  writeFileSync(
    join(work, 'tsconfig.json'),
    JSON.stringify({
      extends: '../tsconfig.json',
      compilerOptions: {
        noEmit: false,
        declaration: true,
        emitDeclarationOnly: true,
        rootDir: '../../..',
        outDir: 'out',
      },
      include: ['expand.ts'],
    }),
  )
  execFileSync(bin('tsc'), ['-p', join(work, 'tsconfig.json')], {
    stdio: 'inherit',
  })
  const emitted = readFileSync(join(work, 'out/packages/sdk/.types-gen/expand.d.ts'), 'utf8')
  if (/\bimport\b|\bz\./.test(emitted)) throw new Error('A type was not fully expanded')
  const docs = contractDocs(join(root, 'tsconfig.json'), join(root, 'src/contract-types.ts'), names)
  writeFileSync(join(root, 'src/types.ts'), typesFile(insertDocs(emitted, docs)))
  writeFileSync(join(root, 'test/types-fidelity.ts'), fidelityFile())
} finally {
  rmSync(work, { recursive: true, force: true })
}
execFileSync(bin('biome'), ['format', '--write', 'src/types.ts', 'test/types-fidelity.ts'], {
  cwd: root,
  stdio: 'inherit',
})

function typesFile(emitted: string): string {
  const body = emitted
    .replace(/^export \{\};?\n?/m, '')
    .replace(/^export declare const (\w+): /gm, 'export type $1 = ')
  return [
    '// Generated by scripts/generate-types.ts from src/contract-types.ts: do not edit.',
    '// Plain request and response types of the SDK, expanded from the Zod contracts (D260).',
    body,
  ].join('\n')
}

function fidelityFile(): string {
  return [
    '// Generated by scripts/generate-types.ts: every plain type of src/types.ts must stay',
    '// mutually assignable with the Zod-derived type it was expanded from. A failure here',
    '// means the contracts changed: run `pnpm --filter @devitek/mailsink generate:types`.',
    "import type * as S from '../src/contract-types'",
    "import type * as G from '../src/types'",
    '',
    'type Same<A, B> = [A] extends [B] ? ([B] extends [A] ? true : false) : false',
    'type Assert<T extends true> = T',
    '',
    'export type Fidelity = [',
    ...names.map((name) => `  Assert<Same<G.${name}, S.${name}>>,`),
    ']',
    '',
  ].join('\n')
}
